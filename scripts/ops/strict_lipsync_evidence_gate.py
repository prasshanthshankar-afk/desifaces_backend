"""DEV-only, fail-closed lip-sync evidence gate.

Accepts only measurements generated by a validated AV evaluator. Does not infer
visual synchronization from waveform offsets or provider success status.
No production routing integration is implied.
"""
from __future__ import annotations
import json
import sys
from pathlib import Path

EXPECTED_TURNS = 6
MAX_MEDIAN_MS = 40.0
MAX_P95_MS = 80.0

def evaluate(report: dict) -> dict:
    turns = report.get("turns")
    reasons = []
    if not isinstance(turns, list) or len(turns) != EXPECTED_TURNS:
        return {"decision": "REVIEW_REQUIRED", "reasons": ["six_turns_required"]}
    for index, turn in enumerate(turns, 1):
        prefix = f"turn_{index}"
        if not isinstance(turn, dict):
            reasons.append(f"{prefix}:missing_evidence")
            continue
        if turn.get("turn") != index or not turn.get("speaker_id"):
            reasons.append(f"{prefix}:speaker_or_turn_missing")
        if turn.get("evaluator_validated") is not True:
            reasons.append(f"{prefix}:unvalidated_evaluator")
        if turn.get("confidence_adequate") is not True:
            reasons.append(f"{prefix}:insufficient_confidence")
        for field, limit in (("median_absolute_av_offset_ms", MAX_MEDIAN_MS),
                             ("p95_absolute_av_offset_ms", MAX_P95_MS)):
            value = turn.get(field)
            if type(value) not in (int, float) or not (0 <= value <= 100000):
                reasons.append(f"{prefix}:{field}_missing")
            elif value > limit:
                reasons.append(f"{prefix}:{field}_exceeded")
        for gate in ("speech_complete", "no_perceptible_lag",
                     "no_progressive_drift", "correct_speaker",
                     "boundaries_clean"):
            if turn.get(gate) is not True:
                reasons.append(f"{prefix}:{gate}_not_passed")
    for gate in ("final_stitch_av_verified", "transition_review_passed",
                 "pricing_regressions_passed", "audio_identity_preserved"):
        if report.get(gate) is not True:
            reasons.append(f"final:{gate}_not_passed")
    return {"decision": "PASS" if not reasons else "REVIEW_REQUIRED",
            "reasons": reasons}

def main() -> int:
    if len(sys.argv) != 2:
        print("Usage: python strict_lipsync_evidence_gate.py REPORT.json", file=sys.stderr)
        return 2
    result = evaluate(json.loads(Path(sys.argv[1]).read_text()))
    print(json.dumps(result, indent=2))
    return 0 if result["decision"] == "PASS" else 1

if __name__ == "__main__":
    raise SystemExit(main())
